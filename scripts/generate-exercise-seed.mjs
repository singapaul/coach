#!/usr/bin/env node
// Regenerates supabase/seeds/01_free_exercise_db.sql from free-exercise-db at a
// pinned commit. The generated SQL is committed, so `supabase db reset` never
// touches the network. Run this only to move to a newer free-exercise-db:
// change COMMIT and SHA256, run `node scripts/generate-exercise-seed.mjs`,
// then `pnpm db:reset && pnpm test`.
//
// free-exercise-db (https://github.com/yuhonas/free-exercise-db) is released
// under the Unlicense (public domain).

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const COMMIT = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const SHA256 = '5bb747e3fc658f095a60dcbf6d53c96627acdcc6ffb6fffde86f7e26995d40bf';
const URL = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${COMMIT}/dist/exercises.json`;

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'seeds', '01_free_exercise_db.sql');

const res = await fetch(URL);
if (!res.ok) throw new Error(`GET ${URL} failed: ${res.status}`);
const body = Buffer.from(await res.arrayBuffer());
const digest = createHash('sha256').update(body).digest('hex');
if (digest !== SHA256) throw new Error(`sha256 mismatch: expected ${SHA256}, got ${digest}`);

const exercises = JSON.parse(body.toString('utf8')).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const text = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const textArray = (vs) => (vs?.length ? `array[${vs.map(text).join(', ')}]` : `'{}'::text[]`);

const rows = exercises.map(
  (e) =>
    `  (${[
      text(e.id),
      text(e.name),
      textArray(e.primaryMuscles),
      textArray(e.secondaryMuscles),
      text(e.equipment),
      text(e.force),
      text(e.mechanic),
      text(e.category),
      text(e.level),
      textArray(e.instructions),
    ].join(', ')})`,
);

const sql = `-- GENERATED by scripts/generate-exercise-seed.mjs. Do not edit by hand.
-- Source: free-exercise-db ${COMMIT} (dist/exercises.json, sha256 ${SHA256}), Unlicense.
-- ${exercises.length} exercises. Safe to run again: unchanged rows are left alone,
-- and movement_pattern / body_region are owned by 02_coach_shortlist.sql.

insert into public.exercises
  (id, name, primary_muscles, secondary_muscles, equipment, force, mechanic, category, level, instructions, source)
select v.*, 'seed'
from (values
${rows.join(',\n')}
) as v (id, name, primary_muscles, secondary_muscles, equipment, force, mechanic, category, level, instructions)
on conflict (id) do update set
  name = excluded.name,
  primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment,
  force = excluded.force,
  mechanic = excluded.mechanic,
  category = excluded.category,
  level = excluded.level,
  instructions = excluded.instructions
where (exercises.name, exercises.primary_muscles, exercises.secondary_muscles, exercises.equipment,
       exercises.force, exercises.mechanic, exercises.category, exercises.level, exercises.instructions)
  is distinct from
      (excluded.name, excluded.primary_muscles, excluded.secondary_muscles, excluded.equipment,
       excluded.force, excluded.mechanic, excluded.category, excluded.level, excluded.instructions);
`;

writeFileSync(out, sql);
console.log(`wrote ${exercises.length} exercises to ${out}`);
